import fs from 'node:fs';
import { spawn } from 'node:child_process';
const cwd='/workspace/work/glyph-tests';
const command='source /workspace/work/validation/sdk/cangjie/envsetup.sh\nCJTUI_GLYPH_FILES=/workspace/work/glyph-tests-evidence/final/logical-files tests/glyphs/run.sh public';
const record={name:'public-final-red',cwd,argv:['bash','-lc',command],start:new Date().toISOString()};
const fd=fs.openSync('/workspace/work/glyph-tests-evidence/final/public-final-red.log','w');
const p=spawn('bash',['-lc',command],{cwd,stdio:['ignore',fd,fd]});
const result=await new Promise(resolve=>p.on('close',(code,signal)=>resolve({code,signal})));
fs.closeSync(fd);
Object.assign(record,result,{end:new Date().toISOString()});
fs.writeFileSync('/workspace/work/glyph-tests-evidence/final/public-final-red.json',JSON.stringify(record,null,2)+'\n');
process.stdout.write(JSON.stringify(record)+'\n');
