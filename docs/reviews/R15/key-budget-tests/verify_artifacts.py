from pathlib import Path
import hashlib,json,subprocess,tempfile,sys,datetime
root=Path('/workspace/work/theme-key-budget-tests/source');raw=root.parent/'raw'
base='51a22fee9732a6d53affd05dd1eaa63e3d58ce2e'
h=lambda data:hashlib.sha256(data).hexdigest()
sys.path.insert(0,str(root/'tests/themes'))
from generate_inputs import generate
from generate_key_budget_inputs import ENCODINGS,CONTEXTS,key_spelling
original=subprocess.check_output(['git','show',base+':tests/themes/generate_inputs.py'],cwd=root)
namespace={'__name__':'baseline_generator'};exec(compile(original,'baseline_generate_inputs.py','exec'),namespace)
with tempfile.TemporaryDirectory(dir=root.parent) as directory:
    old=Path(directory)/'old';new=Path(directory)/'new'
    namespace['generate'](old);generate(new)
    old_hashes={str(p.relative_to(old)):h(p.read_bytes()) for p in old.rglob('*') if p.is_file()}
    new_hashes={str(p.relative_to(new)):h(p.read_bytes()) for p in new.rglob('*') if p.is_file()}
    assert all(new_hashes.get(name)==value for name,value in old_hashes.items())
    added=set(new_hashes)-set(old_hashes);assert len(added)==151,len(added)
    assert all(name.startswith('key-budget-') for name in added)
    (raw/'generated-preservation.json').write_text(json.dumps(dict(original=old_hashes,added={name:new_hashes[name] for name in sorted(added)},unchanged=True),indent=2)+'\n')
    arithmetic=[]
    for encoding in ENCODINGS:
        for size in (1024,1025):
            key=key_spelling(encoding,size);payload=key if encoding=='bare' else key[1:-1]
            assert len(payload.encode())==size
            arithmetic.append(dict(encoding=encoding,payload_bytes=size,source_key_runes=len(key),source_key_bytes=len(key.encode()),contexts=list(CONTEXTS)))
    (raw/'key-byte-arithmetic.json').write_text(json.dumps(arithmetic,indent=2)+'\n')
files=subprocess.check_output(['git','ls-tree','-r','--name-only',base,'--','tests/themes'],cwd=root,text=True).splitlines()
allowed={
 'tests/themes/generate_inputs.py':[(b'from generate_key_budget_inputs import generate_key_budget\n',b''),(b'    # T009 encoded-key resource supplement; existing generated bytes stay fixed.\n    generate_key_budget(directory)\n\n',b'')],
 'tests/themes/values/src/capacity_boundaries.cj':[(b'    encodedKeyBudgetBoundaries()\n',b'')],
}
records=[]
for name in files:
    before=subprocess.check_output(['git','show',base+':'+name],cwd=root)
    data=(root/name).read_bytes();restored=data
    for addition,replacement in allowed.get(name,[]):
        assert restored.count(addition)==1,name
        restored=restored.replace(addition,replacement)
    assert before==restored,name
    records.append(dict(path=name,base_sha256=h(before),current_sha256=h(data),old_content_preserved=True,additive_hook=name in allowed))
(raw/'source-preservation.json').write_text(json.dumps(records,indent=2)+'\n')
product=subprocess.check_output(['git','diff','--name-only','b3b24f896672336797cec009cfe0cd830a955aa7',base,'--','src','native','build.cj','cjpm.toml'],cwd=root,text=True)
assert product=='',product
(raw/'root-build-reuse.json').write_text(json.dumps(dict(product_diff_from_previous_actual_root_build=product,reference='/workspace/work/theme-glyph-tests/raw/refresh-offline/commands.jsonl',reason='identical src/native/build.cj/cjpm.toml; SDK1.2/stdx/UCD and original dependencies unchanged; no full cold build replay'),indent=2)+'\n')
print(f'PASS: {len(files)} former Theme/Glyph files preserve all bytes/assertions (two additive hooks)')
print(f'PASS: {len(old_hashes)} original generated files unchanged; 151 additive inputs')
print('PASS: 22 independently calculated payload lengths x 6 contexts; raw1030/103 arithmetic')
